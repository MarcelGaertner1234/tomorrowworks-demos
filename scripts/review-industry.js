async (page) => {
  await page.route('http://127.0.0.1:4173/**',r=>r.continue());
  const results=[],errors=[],writes=[];
  const error=e=>errors.push(e.message),request=r=>{if(!['GET','HEAD'].includes(r.method()))writes.push(r.url());};
  page.on('pageerror',error);page.on('request',request);
  await page.setViewportSize({width:1440,height:1050});
  const goto=p=>page.goto('http://127.0.0.1:4173/'+p,{waitUntil:'networkidle'});
  const assert=(v,m)=>{if(!v)throw Error(m);};
  const run=async(name,fn)=>{try{await fn();results.push({name,pass:true});}catch(e){results.push({name,pass:false,error:e.message});}};
  await goto('jost-maler/');
  await page.evaluate(()=>['jost-maler','clean-cut','mos-kebab'].forEach(s=>sessionStorage.removeItem('tw-workflow-v1:'+s)));
  await run('Jost: Raumdaten, Konflikt, Besichtigung, Entwurf, Neuladen',async()=>{
    await goto('jost-maler/anfrage.html?leistung=innenraum&inspiration=salbei');
    await page.locator('#ort').fill('Beispielort');await page.locator('#zeitraum').selectOption('1-3-monate');
    await page.locator('#projekt-flaeche').fill('48');await page.locator('#projekt-untergrund').selectOption({label:'Gestrichener Putz'});
    await page.locator('#vorname').fill('Demo');await page.locator('#nachname').fill('Beispiel');await page.locator('#handy').fill('01512345678');
    await page.locator('form button[type=submit]').click();
    assert(await page.locator('[data-flow-handoff]').isVisible(),'Übergabe fehlt');
    const record=await page.evaluate(()=>DemoFlow.latest('jost-maler'));
    assert(record.area===48&&record.notes.includes('Salbeigrün'),'Raumdaten fehlen');
    assert(!JSON.stringify(record).includes('01512345678'),'Telefon gespeichert');
    await page.locator('[data-flow-handoff] a').first().click();await page.waitForLoadState('networkidle');
    await page.locator('#visit-time').selectOption('10:00');await page.locator('[data-visit-form] button').click();
    assert(await page.locator('[data-visit-error]').isVisible(),'Konflikt nicht erkannt');
    await page.locator('#visit-time').selectOption('11:00');await page.locator('[data-visit-form] button').click();
    assert((await page.locator('[data-visit-result]').innerText()).includes('geplant'),'Termin nicht geplant');
    await page.locator('[data-draft]').click();
    await page.screenshot({path:'/Users/marcelgaertner/neuwerk/.worktrees/tomorrowworks-demos/output/branchen/jost-desktop.png'});
    await page.locator('.wf-paper > a').click();await page.reload();
    assert((await page.locator('[data-wf-customer]').innerText()).includes('48 m²'),'Raumfläche fehlt nach Reload');
    assert((await page.locator('[data-wf-customer]').innerText()).includes('Angebotsentwurf vorbereitet'),'Kundenstatus fehlt');
  });
  await run('Clean Cut: Buchung, Doppelabschluss, Kalender, Konflikt, Verschieben, Absage',async()=>{
    await goto('clean-cut/termin.html');
    await page.locator('[data-day="Dienstag"]').click();await page.locator('[data-time="09:30"]').click();
    await page.locator('#vorname').fill('Demo');await page.locator('#nachname').fill('Beispiel');await page.locator('#handy').fill('01512345678');
    const slot=page.locator('[data-slot][aria-pressed]').first();const oldtime=await slot.getAttribute('data-slot');
    await slot.click();await page.locator('[data-confirm]').click();await page.locator('[data-confirm]').click();
    const records=await page.evaluate(()=>DemoFlow.list('clean-cut'));
    assert(records.length===1,'Doppelter Vorgang');const id=records[0].id;
    assert(records[0].duration===45,'Dauer nicht berücksichtigt');
    await page.locator('[data-flow-handoff] a').first().click();await page.waitForLoadState('networkidle');
    assert(await page.locator('[data-booking="'+id+'"]').isVisible(),'Termin nicht im Kalender');
    await page.locator('#move-time').selectOption('09:00');await page.locator('[data-move-form] button[type=submit]').click();
    assert(await page.locator('[data-move-error]').isVisible(),'Konflikt nicht erkannt');
    await page.locator('#move-day').selectOption('do');await page.locator('#move-time').selectOption('12:00');await page.locator('[data-move-form] button[type=submit]').click();
    assert((await page.locator('[data-move-result]').innerText()).includes('verschoben'),'Nicht verschoben');
    await page.screenshot({path:'/Users/marcelgaertner/neuwerk/.worktrees/tomorrowworks-demos/output/branchen/clean-desktop.png',fullPage:true});
    await goto('clean-cut/termin.html');
    assert(await page.locator('[data-slot="'+oldtime+'"]').getAttribute('aria-disabled')!=='true','Alter Platz nicht frei');
    await page.locator('[data-tag="do"]').click();
    assert(await page.locator('[data-slot="12:00"]').getAttribute('aria-disabled')==='true','Neuer Platz noch frei');
    await goto('clean-cut/vorgang.html?id='+id);
    assert((await page.locator('[data-wf-customer]').innerText()).includes('Donnerstag'),'Kundenstatus nicht geändert');
    await page.locator('.wf-side .wf-button').click();await page.waitForLoadState('networkidle');await page.locator('[data-cancel]').click();
    assert((await page.locator('[data-move-result]').innerText()).includes('abgesagt'),'Absage fehlt');
    await goto('clean-cut/termin.html');await page.locator('[data-tag="do"]').click();
    assert(await page.locator('[data-slot="12:00"]').getAttribute('aria-disabled')!=='true','Absage gibt Zeit nicht frei');
  });
  await run('MOS: Bon, Sonderwunsch, Küchenaktionen, Kundenstatus',async()=>{
    await goto('mos-kebab/');
    await page.locator('[data-warenkorb-plus]').first().click();await page.locator('[data-warenkorb-toggle]').click();await page.locator('[data-warenkorb-abschliessen]').click();
    await page.locator('[data-flow-slots] .slot-pille').first().click();
    await page.locator('[name="flow-name"]').fill('Demo');await page.locator('[name="flow-telefon"]').fill('01512345678');
    await page.locator('#bestell-wunsch').fill('Ohne Zwiebeln');
    await page.locator('[data-flow-weiter]').click();
    const r=await page.evaluate(()=>DemoFlow.latest('mos-kebab'));
    assert(r.items.length===1&&r.notes==='Ohne Zwiebeln','Bon unvollständig');
    assert(await page.locator('[data-warenkorb-leiste]').isHidden(),'Warenkorb nach Abschluss nicht leer');
    await page.locator('[data-flow-handoff] a').first().click();await page.waitForLoadState('networkidle');
    assert((await page.locator('.wf-ticket').innerText()).includes('Ohne Zwiebeln'),'Sonderwunsch fehlt');
    await page.screenshot({path:'/Users/marcelgaertner/neuwerk/.worktrees/tomorrowworks-demos/output/branchen/mos-desktop.png'});
    await page.locator('[data-next="cooking"]').click();await page.reload();
    assert(await page.locator('[data-next="ready"]').isVisible(),'Zubereitung nicht gespeichert');
    await page.locator('[data-next="ready"]').click();await page.locator('.wf-ticket .wf-link').click();await page.waitForLoadState('networkidle');
    assert((await page.locator('[data-wf-customer]').innerText()).includes('Abholbereit'),'Kundenstatus unverändert');
    await page.locator('.wf-side .wf-button').click();await page.waitForLoadState('networkidle');await page.locator('[data-next="collected"]').click();
    assert((await page.locator('.wf-archive').innerText()).includes(r.id),'Abschluss fehlt');
  });
  page.off('pageerror',error);page.off('request',request);
  return {results,errors,writes};
}
